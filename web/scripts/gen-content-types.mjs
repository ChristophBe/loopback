// Generates src/gen/content.ts from the content schemas in ../api/schemas.
import { writeFileSync } from 'node:fs'
import { compileFromFile } from 'json-schema-to-typescript'

const names = ['lesson', 'quiz', 'flashcard', 'review', 'check-result']
const banner = '// Generated by scripts/gen-content-types.mjs from api/schemas. DO NOT EDIT.\n'

const parts = []
for (const name of names) {
  const file = new URL(`../../api/schemas/${name}.schema.json`, import.meta.url).pathname
  parts.push(
    await compileFromFile(file, {
      bannerComment: '',
      additionalProperties: false,
      ignoreMinAndMaxItems: true,
    }),
  )
}
writeFileSync(new URL('../src/gen/content.ts', import.meta.url), banner + '\n' + parts.join('\n'))
